// Находим форму на HTML-странице по её id.
// В переменной form теперь находится HTML-элемент <form>.
const form = document.querySelector("#orderForm");


// Добавляем обработчик события submit.
// Событие submit происходит, когда пользователь
// нажимает кнопку "Оформить заказ".
form.addEventListener("submit", function (event) {

    // Отменяем стандартную отправку формы.
    // Без preventDefault() браузер отправит форму
    // стандартным способом и страница перезагрузится.
    event.preventDefault();


    // -----------------------------------------
    // 1. ПОЛУЧАЕМ ЗНАЧЕНИЕ INPUT TYPE="TEXT"
    // -----------------------------------------

    // Находим поле с id="userName".
    // Свойство value содержит введённый пользователем текст.
    // trim() удаляет лишние пробелы в начале и конце строки.
    const userName = document
        .querySelector("#userName")
        .value
        .trim();


    // -----------------------------------------
    // 2. ПОЛУЧАЕМ ЗНАЧЕНИЕ INPUT TYPE="EMAIL"
    // -----------------------------------------

    // Значение email также получаем через value.
    // trim() удаляет лишние пробелы.
    // toLowerCase() переводит email в нижний регистр.
    const email = document
        .querySelector("#email")
        .value
        .trim()
        .toLowerCase();


    // -----------------------------------------
    // 3. ПОЛУЧАЕМ ЗНАЧЕНИЕ INPUT TYPE="PASSWORD"
    // -----------------------------------------

    // Несмотря на то что браузер скрывает символы пароля,
    // его значение также получается через свойство value.
    const password = document
        .querySelector("#password")
        .value;


    // -----------------------------------------
    // 4. ПОЛУЧАЕМ ТЕКСТ ИЗ TEXTAREA
    // -----------------------------------------

    // textarea работает с JavaScript аналогично
    // обычному текстовому полю.
    // Введённый текст находится в свойстве value.
    const comment = document
        .querySelector("#comment")
        .value
        .trim();


    // -----------------------------------------
    // 5. ПОЛУЧАЕМ ЗНАЧЕНИЕ SELECT
    // -----------------------------------------

    // У обычного select свойство value содержит
    // value выбранного элемента <option>.
    const delivery = document
        .querySelector("#delivery")
        .value;


    // -----------------------------------------
    // 6. ПОЛУЧАЕМ ВЫБРАННЫЙ RADIO
    // -----------------------------------------

    // У radio несколько элементов имеют одинаковый name.
    // :checked позволяет найти именно тот radio,
    // который выбрал пользователь.
    const paymentInput = document.querySelector(
        'input[name="payment"]:checked'
    );

    // Пользователь может не выбрать ни один вариант.
    // Поэтому сначала проверяем, найден ли выбранный radio.
    let payment = "";

    if (paymentInput) {
        // Если radio выбран, получаем его value.
        payment = paymentInput.value;
    }


    // -----------------------------------------
    // 7. ПОЛУЧАЕМ SELECT MULTIPLE
    // -----------------------------------------

    // Находим список, в котором разрешено
    // выбирать несколько значений.
    const categoriesSelect =
        document.querySelector("#categories");

    // Создаём пустой массив.
    // В него будем добавлять выбранные категории.
    const categories = [];

    // selectedOptions содержит только те option,
    // которые выбрал пользователь.
    for (const option of categoriesSelect.selectedOptions) {

        // Добавляем value выбранного option в массив.
        categories.push(option.value);
    }


    // -----------------------------------------
    // 8. ПОЛУЧАЕМ СОСТОЯНИЕ CHECKBOX
    // -----------------------------------------

    // Для checkbox используется свойство checked.
    // Оно возвращает true, если флажок установлен,
    // и false, если флажок не установлен.
    const agreement = document
        .querySelector("#agreement")
        .checked;


    // -----------------------------------------
    // 9. ПРОВЕРЯЕМ ОБЯЗАТЕЛЬНЫЕ ПОЛЯ
    // -----------------------------------------

    // Проверяем имя и email.
    // Пустая строка означает, что поле не заполнено.
    if (userName === "" || email === "") {
        console.log("Заполните имя и email");
        return;
    }


    // Проверяем пароль.
    if (password === "") {
        console.log("Введите пароль");
        return;
    }


    // Проверяем длину пароля.
    if (password.length < 8) {
        console.log(
            "Пароль должен содержать не менее 8 символов"
        );

        return;
    }


    // Проверяем, выбран ли способ доставки.
    if (delivery === "") {
        console.log("Выберите способ доставки");
        return;
    }


    // Проверяем, выбран ли способ оплаты.
    if (payment === "") {
        console.log("Выберите способ оплаты");
        return;
    }


    // Проверяем checkbox.
    // Если agreement содержит false,
    // пользователь не принял условия.
    if (!agreement) {
        console.log(
            "Необходимо принять условия оформления заказа"
        );

        return;
    }


    // -----------------------------------------
    // 10. СОЗДАЁМ ОБЪЕКТ
    // -----------------------------------------

    // Все полученные данные объединяем
    // в один объект JavaScript.
    const order = {
        userName,
        email,
        password,
        comment,
        delivery,
        payment,
        categories,
        agreement
    };


    // -----------------------------------------
    // 11. ВЫВОДИМ ОБЪЕКТ
    // -----------------------------------------

    console.log("Данные заказа:");
    console.log(order);


    // -----------------------------------------
    // 12. ПРЕОБРАЗУЕМ ОБЪЕКТ В JSON
    // -----------------------------------------

    // JSON.stringify() преобразует объект JavaScript
    // в JSON-строку.
    const json = JSON.stringify(order);


    // Выводим полученный JSON.
    console.log("JSON:");
    console.log(json);
});